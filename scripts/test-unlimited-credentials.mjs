import assert from 'node:assert/strict';
import fs from 'node:fs';import os from 'node:os';import path from 'node:path';
import {saveCredential,credentialInventory,deleteCredential} from '../server/credential-tools.mjs';
import {readClientRecord,saveClientRecord} from '../server/client-credentials.mjs';
process.env.LD_CREDENTIALS_FILE=path.join(fs.mkdtempSync(path.join(os.tmpdir(),'ld-credentials-test-')),'fixture.json');
const staff={role:'staff'};
saveClientRecord('fixture',{other1_name:'Existing',other1_password:'fixture-original'},staff);
for(let i=2;i<=250;i++)assert.equal(saveCredential('fixture',{name:`Account ${i}`,username:`user${i}`,password:'fixture-secret',notes:'fixture 2FA note'}).slot,`other${i}`);
assert.equal(credentialInventory('fixture').count,250);
assert.equal(saveCredential('fixture',{name:' account 200 ',url:'https://example.test'}).slot,'other200');
const fields=readClientRecord('fixture',staff).fields;
assert.equal(fields.other1_password,'fixture-original');assert.equal(fields.other200_password,'fixture-secret');assert.equal(fields.other200_notes,'fixture 2FA note');
assert.ok(!JSON.stringify(credentialInventory('fixture')).includes('fixture-secret'));
assert.throws(()=>saveClientRecord('fixture',{other251_password:'x'},{role:'client'}),/Forbidden/);
assert.throws(()=>saveClientRecord('fixture',{other0_password:'x'},staff),/Invalid field/);
deleteCredential('fixture','other200');assert.equal(credentialInventory('fixture').count,249);
assert.equal(saveCredential('fixture',{name:'Replacement'}).slot,'other200');
assert.equal(readClientRecord('fixture',staff).fields.other200_notes,'');
console.log('PASS: 250 accounts, preserved secrets, partial updates, private notes, redaction, authorization, deletion and slot reuse.');
